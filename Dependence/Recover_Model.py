class Recover_Model_dae:
    def __init__(self,candidate_lib_full:pd.DataFrame,data_derivatives:pd.DataFrame,coef_threshold,threshold_scan):
        # data_derivatives: dataframe generated by Comparison.compute_time_derivatives
        # threshold: coefficient threshold, depends on parameter values
        self.candidate_lib_full = candidate_lib_full
        self.data_derivatives = data_derivatives
        self.coef_threshold = coef_threshold
        self.threshold_scan = threshold_scan

        self.mapping, self.model_expression = self._recovered_model()
        self.model = self._model_to_dataframe()
    
    def _recovered_equation(self,target_column):
        seq_th_model = sequentialThLin(
            model_id = "RR",
            coef_threshold = self.coef_threshold,
            fit_intercept = False
        )
        #print("DEBUG – created STLSQ with coef_threshold =", seq_th_model.coef_threshold)
        seq_th_model.fit(self.candidate_lib_full,self.data_derivatives[target_column])

        final_coef = seq_th_model.coef_history_df.iloc[-1].fillna(0.0)
        discovered_terms = final_coef[final_coef != 0]
        # Build RHS string with correct ± signs
        rhs_terms = []
        for name, coef in discovered_terms.items():
            sign = "+" if coef >= 0 else "-"
            rhs_terms.append(f"{sign} {abs(coef):.4g}*{name}")
        rhs = " ".join(rhs_terms).lstrip("+ ").replace("+ -", "- ")

        equation = f"{target_column} = {rhs}"
        return discovered_terms,equation
    
    def _recovered_model(self):
        col_feature = [col for col in self.data_derivatives.columns if col not in ['t_Exp','t_Sim']]
        self.features = col_feature
        mapping = {}
        for feature in col_feature:
            discovered_terms,equation = self._recovered_equation(target_column=feature)
            mapping[feature] = {
                'discovered_terms': discovered_terms,
                'equation': equation
            }
        model_expression = "\n".join(
            mapping[feature]['equation'] for feature in col_feature
        )
        return mapping, model_expression
    
    def _model_to_dataframe(self):
        rows = []
        for feature in self.features:
            equation = self.mapping[feature]['equation']
            lhs,rhs = equation.split('=',1)
            rows.append({'Variable':lhs.strip(),
                        'Equation':rhs.strip()})
        return pd.DataFrame(rows)


class Recover_Model_sindy:
    def __init__(self,data,differential_order,poly_degree,threshold,threshold_scan=None,Xdot=None,method='Monomial'):
        # data: DataFrame -- contains all columns including states and time
        # method: basis library used, the default one is monomial library
        self.data = data
        self.differential_order = differential_order
        self.poly_degree = poly_degree
        self.threshold = threshold
        self.threshold_scan = threshold_scan
        self.Xdot = Xdot
        self.method = method

        self.data_states, self.time = self._preprocess()

        if method == 'Monomial':
            self.model_expression = self._recovered_model_monomial()
        else:
            self.model_expression = self._recovered_model_orthogonal()

    def _preprocess(self):
        data, time_col = standardize_columns(self.data)
        if isinstance(time_col, list):
            self.time_col_name = time_col[0]
        else:
            time_col_name = time_col
        time = data[time_col_name].to_numpy()
        data_states = data.copy().drop(columns={time_col})

        self.features = data_states.columns.tolist()
        if self.method == 'Chebyshev' or self.method == 'Legendre':
            self.data_norm, self.L, self.U = normalization(data_states)
        return data_states, time
    
    def _recovered_model_monomial(self):
        #differential_method = ps.FiniteDifference(self.differential_order)
        feature_library = ps.PolynomialLibrary(self.poly_degree,include_bias=False)
        optimizer = ps.STLSQ(threshold=self.threshold)
        feature_names = self.features

        X = np.array(self.data_states, dtype=np.float64)
        t = np.array(self.time, dtype=np.float64).reshape(-1)
        dt = t[1] - t[0]
        
        if self.Xdot is None:
            X_dot = np.gradient(X,t,axis=0,edge_order=self.differential_order)
            model = ps.SINDy(
                #differentiation_method=differential_method,
                feature_library = feature_library,
                optimizer = optimizer,
                feature_names = feature_names
            )
            self.model = model
            model.fit(X,t=t,x_dot=X_dot)
            #model.fit(self.data_states,t = self.time)
        else:
            model = ps.SINDy(
                feature_library=feature_library,
                optimizer=optimizer,
                feature_names=feature_names
            )
            self.model = model
            model.fit(self.data_states,t=t,x_dot=self.Xdot)
        eq_list = model.equations()

        states, rhs_raw = [], []
        for var, eq in zip(model.feature_names, eq_list):
            states.append(f'd{var}/dt')
            rhs_raw.append(eq.strip())
        def clean(eq: str) -> str:
            eq = re.sub(r'\+\s+-', '- ', eq)
            eq = re.sub(r'\s+', ' ', eq).strip()
            return eq
        rhs = [clean(s) for s in rhs_raw]
        df = pd.DataFrame({
            'Varaiable': states,
            'Equation': rhs
        })
        return df
    
    def _recovered_model_orthogonal(self):
        differential_method = ps.FiniteDifference(self.differential_order)
        if self.method == 'Chebyshev':
            feature_library = OrthogonalLibrary(degree=self.poly_degree,method='Chebyshev')
        elif self.method == 'Legendre':
            feature_library = OrthogonalLibrary(degree=self.poly_degree,method='Legendre')
        optimizer = ps.STLSQ(threshold=self.threshold)
        feature_names = self.features

        model = ps.SINDy(
            differentiation_method=differential_method,
            feature_library=feature_library,
            optimizer=optimizer,
            feature_names=feature_names
        )
        self.model = model
        model.fit(self.data_norm,t=self.time)
        eq_list = model.equations()

        converter = ChebyshevToPolynomialConverter(max_degree=self.poly_degree)
        polynomial_model = converter.convert_sindy_model(eq_list)

        denormalizer = EquationDenormalizer(self.L,self.U)
        equation_list = [f"d{var}/dt = {poly._to_string()}" for var, poly in polynomial_model.items()]
        original_equations = denormalizer.denormalize_equations(equation_list)

        states, rhs_raw = [], []
        for var, eq in zip(model.feature_names, original_equations):
            parts = eq.split('=')
            states.append(f'd{var}/dt')
            rhs_raw.append(parts[1].strip())
        def clean(eq: str) -> str:
            eq = re.sub(r'\+\s+-', '- ', eq)
            eq = re.sub(r'\s+', ' ', eq).strip()
            return eq
        rhs = [clean(s) for s in rhs_raw]
        df = pd.DataFrame({
            'Varaiable': states,
            'Equation': rhs
        })
        return df

    def _plot_pareto(self):
        """Compute Pareto-like curves of error vs threshold.
        This version fits a fresh model for each threshold and computes scores immediately,
        avoiding the fragile pattern of reusing a single optimizer/model afterward.
        """
        import numpy as _np
        import matplotlib.pyplot as _plt
        from sklearn.metrics import mean_squared_error as _mse

        # Train/test split on index (no shuffle to preserve time ordering)
        indices = _np.arange(len(self.data_states))
        train_indices, test_indices = train_test_split(
            indices, test_size=0.33, random_state=27, shuffle=False
        )

        # Prepare data by basis type
        method = self.method
        feature_names = self.features
        t = self.time
        t_train = t[train_indices]
        t_test = t[test_indices]

        # Prepare X / Xdot on the appropriate space
        if method == 'Monomial':
            X_all = _np.asarray(self.data_states, dtype=_np.float64)
            if self.Xdot is None:
                Xdot_all = _np.gradient(X_all, t, axis=0, edge_order=self.differential_order)
            else:
                Xdot_all = _np.asarray(self.Xdot, dtype=_np.float64)
            X_train, X_test = X_all[train_indices], X_all[test_indices]
            Xdot_train, Xdot_test = Xdot_all[train_indices], Xdot_all[test_indices]
            feature_library = ps.PolynomialLibrary(self.poly_degree, include_bias=False)
        elif method in ('Chebyshev', 'Legendre'):
            # Use normalized data for orthogonal libraries
            X_all = _np.asarray(self.data_norm, dtype=_np.float64)
            # For fair scoring, compute derivative in the same normalized space
            Xdot_all = _np.gradient(X_all, t, axis=0, edge_order=self.differential_order)
            X_train, X_test = X_all[train_indices], X_all[test_indices]
            Xdot_train, Xdot_test = Xdot_all[train_indices], Xdot_all[test_indices]
            feature_library = OrthogonalLibrary(degree=self.poly_degree, method=method)
        else:
            raise ValueError(f"Unknown method: {method}")

        thresholds = self.threshold_scan if self.threshold_scan is not None else [self.threshold]
        mse_deriv = _np.zeros(len(thresholds))
        mse_traj = _np.zeros(len(thresholds))

        for k, thr in enumerate(thresholds):
            optimizer = ps.STLSQ(threshold=thr)
            model = ps.SINDy(
                feature_library=feature_library,
                optimizer=optimizer,
                feature_names=feature_names,
            )
            # Fit on training set
            model.fit(X_train, t=t_train, x_dot=Xdot_train)

            # 1) Derivative-domain error on test set
            try:
                mse_deriv[k] = model.score(X_test, t=t_test, x_dot=Xdot_test, metric=_mse)
            except Exception:
                # If score fails (shape mismatch, etc.), fall back to manual MSE
                Xdot_pred = model.predict(X_test)
                mse_deriv[k] = _np.mean((Xdot_test - Xdot_pred) ** 2)

            # 2) Trajectory-domain error on test set via simulate
            try:
                x0 = X_test[0]
                X_sim = model.simulate(x0, t_test, integrator="odeint")
                # If simulate explodes, clip to avoid NaNs in MSE
                if _np.any(~_np.isfinite(X_sim)) or _np.any(_np.abs(X_sim) > 1e6):
                    X_sim = _np.clip(X_sim, -1e6, 1e6)
                mse_traj[k] = _np.mean((X_test - X_sim) ** 2)
            except Exception:
                mse_traj[k] = _np.nan

        # Plot (do not rely on external helper)
        _plt.figure()
        _plt.semilogy(thresholds, mse_deriv, "o-", label=r"$\dot{X}$ RMSE")
        _plt.xlabel(r"$\lambda$")
        _plt.xticks(thresholds, [f"{v:.1e}" for v in thresholds])
        _plt.ylabel(r"Error")
        _plt.title("Derivative-domain error vs threshold")
        _plt.grid(True, alpha=0.3)
        _plt.tight_layout()

        _plt.figure()
        _plt.semilogy(thresholds, mse_traj, "o-", label="Trajectory RMSE")
        _plt.xlabel(r"$\lambda$")
        _plt.ylabel("Error")
        _plt.xticks(thresholds, [f"{v:.1e}" for v in thresholds])
        _plt.title("Trajectory-domain error vs threshold")
        _plt.grid(True, alpha=0.3)
        _plt.tight_layout()

        return thresholds, mse_deriv, mse_traj
    

def plot_pareto(coefs, opt, model, threshold_scan, x_test, t_test):
        #formatter = LogFormatterExponent(base=10)
        mse = np.zeros(len(threshold_scan))
        mse_sim = np.zeros(len(threshold_scan))
        for i in range(len(threshold_scan)):
            opt.coef_ = coefs[i]
            mse[i] = model.score(x_test, t=t_test, metric=mean_squared_error)
            x_test_sim = model.simulate(x_test.iloc[0].to_numpy(), t_test, integrator="odeint")
            if np.any(x_test_sim > 1e4):
                x_test_sim = 1e4
            # Ensure subtraction is performed on compatible NumPy arrays and result is a scalar
            mse_sim[i] = np.mean((x_test.values - x_test_sim) ** 2)
        plt.figure()
        plt.semilogy(threshold_scan, mse, "bo")
        plt.semilogy(threshold_scan, mse, "b")
        plt.ylabel(r"$\dot{X}$ RMSE", fontsize=20)
        plt.xlabel(r"$\lambda$", fontsize=20)
        plt.xticks(fontsize=14, rotation=45) 
